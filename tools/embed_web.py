"""Generate PROGMEM assets; --check verifies the committed header without editing it."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
ASSETS = {'index.html': 'PAGE_INDEX', 'wifi.html': 'PAGE_WIFI', 'mqtt.html': 'PAGE_MQTT',
          'app.js': 'ASSET_APP_JS', 'app.css': 'ASSET_APP_CSS'}

def generate():
    result = '// SPDX-License-Identifier: 0BSD\n// Generated by tools/embed_web.py. Edit web/* instead.\n#pragma once\n'
    for name, symbol in ASSETS.items():
        content = (ROOT / 'web' / name).read_text(encoding='utf-8')
        if ')WEBASSET"' in content:
            raise ValueError('Raw string delimiter occurs in asset')
        result += f'\nstatic const char {symbol}[] PROGMEM = R"WEBASSET({content})WEBASSET";\n'
    return result

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'esp32_photo-frame' / 'web_assets.h'
    generated = generate()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != generated:
            raise SystemExit('web_assets.h is stale; run python tools/embed_web.py')
        print('Embedded web assets match their sources.')
    else:
        target.write_text(generated, encoding='utf-8', newline='\n')
